// Measure a string in cap-height units (before scaling).
function letterWidth(text, tracking = 8) {
  let w = 0;
  for (const ch of text) { const g = GLYPH[ch] || GLYPH['-']; w += g[0] + tracking; }
  return w - (text.length ? tracking : 0);
}

// Lay a string out as brush strokes. Returns {strokes, width} in logical units,
// already placed at (x,y) with the requested size, alignment and per-letter hand jitter.
function letterLayout(text, x, y, { size = 48, align = 'left', tracking = 8, seed = 1, jitter = 1 } = {}) {
  const k = size / 100, total = letterWidth(text, tracking) * k;
  let px = align === 'center' ? x - total / 2 : align === 'right' ? x - total : x;
  const out = [];
  let idx = 0;
  for (const ch of text) {
    const g = GLYPH[ch] || GLYPH['-'];
    // Each letter sits slightly off the line, a hair rotated and a hair bigger or smaller.
    const bob = (hash(idx, seed) - .5) * 4.2 * jitter, rot = (hash(idx, seed + 3) - .5) * .055 * jitter;
    const sc = 1 + (hash(idx, seed + 7) - .5) * .06 * jitter, slant = (hash(idx, seed + 11) - .5) * .05 * jitter;
    const ca = Math.cos(rot), sa = Math.sin(rot);
    for (const st of g[1]) {
      out.push(st.map(([gx, gy]) => {
        const a = (gx + gy * slant) * k * sc, b = gy * k * sc;
        return [px + a * ca - b * sa, y + bob + a * sa + b * ca];
      }));
    }
    px += (g[0] + tracking) * k;
    idx++;
  }
  return { strokes: out, width: total };
}

// Draw hand lettering. `p` writes it on stroke by stroke; `boil` is a seed that
// changes a few times a second so the line breathes without moving the letters.
function letterText(c, text, x, y, o = {}) {
  const { size = 48, color = PAL.ink, w = null, p = 1, seed = 1, boil = 0, al = 1, align = 'left', tracking = 8, jitter = 1 } = o;
  if (p <= 0) return 0;
  const { strokes, width } = letterLayout(text, x, y, { size, align, tracking, seed, jitter });
  const lens = strokes.map(s => Math.max(6, pathLength(s) + size * .18));
  const total = lens.reduce((a, b) => a + b, 0);
  const want = total * clamp(p, 0, 1);
  const nib = w ?? Math.max(1.5, size * .052);
  let acc = 0;
  for (const [i, s] of strokes.entries()) {
    const local = clamp((want - acc) / lens[i], 0, 1); acc += lens[i];
    if (local <= 0) break;
    brush(c, s, { w: nib, color, p: local, seed: seed * 31 + i * 7 + boil, amp: size * .012, taper: .8, al });
  }
  return width;
}
